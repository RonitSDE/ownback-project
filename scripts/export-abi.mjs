// Copies compiled ABIs from contracts/out into typed TS modules for viem.
// Run after `forge build`: npm run abi
import { readFileSync, writeFileSync } from 'node:fs';

const contracts = {
  ownbackAbi: 'Ownback.sol/Ownback.json',
  usdcAbi: 'MockUSDC.sol/MockUSDC.json',
  stockAbi: 'MockB20Stock.sol/MockB20Stock.json',
  adapterAbi: 'PricedMockStockAdapter.sol/PricedMockStockAdapter.json',
};

let out = '// Generated by scripts/export-abi.mjs from contracts/out. Do not edit by hand.\n\n';
for (const [name, path] of Object.entries(contracts)) {
  const { abi } = JSON.parse(readFileSync(new URL(`../contracts/out/${path}`, import.meta.url)));
  out += `export const ${name} = ${JSON.stringify(abi, null, 2)} as const;\n\n`;
}
writeFileSync(new URL('../src/lib/abi/index.ts', import.meta.url), out);
console.log('Wrote src/lib/abi/index.ts');
